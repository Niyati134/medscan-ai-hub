import { createFileRoute, Link } from "@tanstack/react-router";
import { useServerFn } from "@tanstack/react-start";
import { useQuery } from "@tanstack/react-query";
import { useMemo } from "react";
import { z } from "zod";
import {
  Printer,
  Phone,
  Droplet,
  AlertTriangle,
  Pill,
  ShieldAlert,
  Download,
  Activity,
} from "lucide-react";
import jsPDF from "jspdf";
import { AppShell } from "@/components/AppShell";
import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { getMyProfile } from "@/lib/profile.functions";
import { listScans, type ParsedMedicine } from "@/lib/scan.functions";
import { listFamilyMembers } from "@/lib/family.functions";
import { ShareDialog } from "@/components/ShareDialog";
import { useAuth } from "@/lib/useAuth";
import { useMember } from "@/lib/useMember";

const searchSchema = z.object({ memberId: z.string().uuid().optional() });

export const Route = createFileRoute("/emergency")({
  validateSearch: (s) => searchSchema.parse(s),
  component: () => (
    <AppShell>
      <EmergencyCard />
    </AppShell>
  ),
});

function EmergencyCard() {
  const { user } = useAuth();
  const { activeMemberId } = useMember();
  const search = Route.useSearch();
  const memberId = search.memberId ?? activeMemberId ?? null;

  const fetchProfile = useServerFn(getMyProfile);
  const fetchScans = useServerFn(listScans);
  const fetchMembers = useServerFn(listFamilyMembers);
  const { data: profile } = useQuery({ queryKey: ["profile"], queryFn: () => fetchProfile() });
  const { data: members = [] } = useQuery({
    queryKey: ["family-members"],
    queryFn: () => fetchMembers(),
  });
  const { data: scans } = useQuery({
    queryKey: ["scans", memberId],
    queryFn: () => fetchScans({ data: { memberId } }),
  });

  const member = memberId ? members.find((m) => m.id === memberId) : null;

  const card = member
    ? {
        name: member.name,
        subline: `${member.relationship}${member.age != null ? ` · ${member.age} yrs` : ""}${member.gender ? ` · ${member.gender}` : ""}`,
        blood: member.blood_group,
        allergies: member.allergies,
        conditions: member.medical_conditions,
        contactName: member.emergency_contact_name,
        contactPhone: member.emergency_contact_phone,
      }
    : {
        name: profile?.display_name ?? user?.email ?? "",
        subline: user?.email ?? "Account owner",
        blood: profile?.blood_group ?? null,
        allergies: profile?.allergies ?? null,
        conditions: null as string | null,
        contactName: profile?.emergency_contact_name ?? null,
        contactPhone: profile?.emergency_contact_phone ?? null,
      };

  const currentMeds = useMemo(() => {
    const latest = (scans ?? []).slice(0, 3);
    const seen = new Set<string>();
    const list: { name: string; dosage: string }[] = [];
    latest.forEach((s) => {
      ((s.medicines as unknown as ParsedMedicine[]) ?? []).forEach((m) => {
        const key = m.name.toLowerCase();
        if (!seen.has(key)) {
          seen.add(key);
          list.push({ name: m.name, dosage: m.dosage });
        }
      });
    });
    return list;
  }, [scans]);

  const downloadPdf = () => {
    const doc = new jsPDF({ unit: "pt", format: "a4" });
    doc.setFillColor(220, 38, 38);
    doc.rect(0, 0, 595, 60, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(22);
    doc.text("EMERGENCY MEDICAL CARD", 40, 38);

    doc.setTextColor(20, 20, 20);
    let y = 100;
    const line = (label: string, value: string) => {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(11);
      doc.text(label.toUpperCase(), 40, y);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(13);
      doc.text(value || "—", 40, y + 18);
      y += 46;
    };
    line("Name", card.name);
    line("Profile", card.subline);
    line("Blood group", card.blood ?? "");
    line("Allergies", card.allergies ?? "");
    line("Medical conditions", card.conditions ?? "");
    line(
      "Emergency contact",
      card.contactName
        ? `${card.contactName} — ${card.contactPhone ?? ""}`
        : card.contactPhone ?? "",
    );

    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.text("CURRENT MEDICATIONS", 40, y);
    y += 18;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(12);
    if (currentMeds.length === 0) {
      doc.text("—", 40, y);
    } else {
      currentMeds.forEach((m) => {
        doc.text(`• ${m.name}${m.dosage ? `  (${m.dosage})` : ""}`, 40, y);
        y += 18;
      });
    }
    doc.setFontSize(9);
    doc.setTextColor(120, 120, 120);
    doc.text(`Generated by MedScan AI · ${new Date().toLocaleString()}`, 40, 800);
    doc.save(`emergency-card-${card.name.replace(/\s+/g, "_").toLowerCase()}.pdf`);
  };

  const share = async () => {
    if (typeof navigator === "undefined" || !navigator.share) {
      await navigator.clipboard?.writeText(
        `EMERGENCY CARD\nName: ${card.name}\nBlood: ${card.blood ?? "—"}\nAllergies: ${card.allergies ?? "—"}\nConditions: ${card.conditions ?? "—"}\nContact: ${card.contactName ?? ""} ${card.contactPhone ?? ""}`,
      );
      return;
    }
    await navigator.share({
      title: `Emergency card — ${card.name}`,
      text: `Blood: ${card.blood ?? "—"} · Allergies: ${card.allergies ?? "—"} · Contact: ${card.contactPhone ?? "—"}`,
    });
  };

  return (
    <div className="mx-auto max-w-3xl space-y-6 animate-fade-up">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <Badge className="mb-2 border-0 bg-destructive/15 text-destructive">
            <ShieldAlert className="mr-1 h-3 w-3" /> In case of emergency
          </Badge>
          <h1 className="font-display text-3xl font-bold tracking-tight">Emergency card</h1>
          <p className="mt-1 text-sm text-muted-foreground">
            One-click printable card with vital information for first responders.
          </p>
        </div>
        <div className="flex flex-wrap gap-2 print:hidden">
          <Button variant="outline" size="sm" onClick={share}>
            Share
          </Button>
          <ShareDialog
            shareType="emergency"
            memberId={memberId}
            defaultTitle={`Emergency card · ${card.name}`}
          />
          <Button variant="outline" size="sm" onClick={() => window.print()}>
            <Printer className="mr-2 h-4 w-4" /> Print
          </Button>
          <Button size="sm" className="bg-gradient-primary" onClick={downloadPdf}>
            <Download className="mr-2 h-4 w-4" /> Download PDF
          </Button>
        </div>
      </div>

      <Card className="overflow-hidden border-destructive/30 shadow-card print:border-2 print:border-destructive">
        <div className="bg-destructive p-5 text-destructive-foreground">
          <p className="text-xs font-bold uppercase tracking-widest opacity-90">
            Medical Emergency Card
          </p>
          <h2 className="font-display text-2xl font-bold">{card.name}</h2>
          <p className="text-xs opacity-90">{card.subline}</p>
        </div>

        <div className="grid gap-5 p-6 sm:grid-cols-2">
          <Field
            icon={<Droplet className="h-4 w-4 text-destructive" />}
            label="Blood group"
            value={card.blood}
          />
          <Field
            icon={<Phone className="h-4 w-4 text-primary" />}
            label="Emergency contact"
            value={
              card.contactName
                ? `${card.contactName}${card.contactPhone ? ` · ${card.contactPhone}` : ""}`
                : card.contactPhone ?? undefined
            }
          />
          <div className="sm:col-span-2">
            <Field
              icon={<AlertTriangle className="h-4 w-4 text-warning" />}
              label="Allergies"
              value={card.allergies}
            />
          </div>
          {card.conditions && (
            <div className="sm:col-span-2">
              <Field
                icon={<Activity className="h-4 w-4 text-primary" />}
                label="Medical conditions"
                value={card.conditions}
              />
            </div>
          )}

          <div className="sm:col-span-2">
            <p className="mb-2 flex items-center gap-2 text-xs font-semibold uppercase tracking-wider text-muted-foreground">
              <Pill className="h-3.5 w-3.5 text-primary" /> Current medications
            </p>
            {currentMeds.length === 0 ? (
              <p className="text-sm text-muted-foreground">No active prescriptions.</p>
            ) : (
              <ul className="space-y-1.5 rounded-xl border border-border bg-muted/30 p-3 text-sm">
                {currentMeds.map((m) => (
                  <li key={m.name} className="flex justify-between gap-3">
                    <span className="font-medium">{m.name}</span>
                    <span className="text-muted-foreground">{m.dosage}</span>
                  </li>
                ))}
              </ul>
            )}
          </div>
        </div>
      </Card>

      {!member && (!profile?.blood_group || !profile?.allergies || !profile?.emergency_contact_phone) && (
        <Card className="glass p-4 print:hidden">
          <p className="text-sm text-muted-foreground">
            Complete your{" "}
            <Link to="/profile" className="font-medium text-primary hover:underline">
              health profile
            </Link>{" "}
            or add a{" "}
            <Link to="/family" className="font-medium text-primary hover:underline">
              family member
            </Link>{" "}
            to make this card more useful.
          </p>
        </Card>
      )}
    </div>
  );
}

function Field({
  icon,
  label,
  value,
}: {
  icon: React.ReactNode;
  label: string;
  value?: string | null;
}) {
  return (
    <div>
      <p className="mb-1 flex items-center gap-2 text-xs font-semibold uppercase tracking-wider text-muted-foreground">
        {icon} {label}
      </p>
      <p className="text-base font-medium">{value || "—"}</p>
    </div>
  );
}
